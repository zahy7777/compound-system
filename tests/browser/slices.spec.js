test('改名删除覆盖全部状态与日期，两个写入阶段失败均可明确重试', async ({page,request}) => {
  await request.post('/writeslice',{data:['训练','福利']})
  const ids = []
  for (const region of ['待办','运行','归档','结果']) ids.push(await seed(request,region,'训练',region))
  await seed(request,'旧日期','训练','归档',[{kind:'属性',text:'备注:保留'}])
  const all = await read(request), old = all.find(event => event.user.event === '旧日期')
  await request.post('/writeevent',{data:[{system:{source_id:old.system.source_id,deleted:false},user:old.user,meta:old.meta.map(value => value.text.startsWith('日期:') ? {...value,text:'日期:2000-01-01'} : value)}]})
  await open(page)
  await page.route('**/writeevent',route => route.fulfill({status:400,json:{error:'标签保存失败'}}))
  await panel(page,'训练').getByRole('button',{name:'修改切片',exact:true}).click(); await dialog(page).locator('input').fill('训练新名'); await dialog(page).getByRole('button',{name:'确定',exact:true}).click()
  await expect(dialog(page).locator('.dialog-error')).toContainText('标签保存失败'); expect(await slices(request)).toEqual(['训练','福利'])
  await page.unroute('**/writeevent')
  await page.route('**/writeslice',route => route.fulfill({status:400,json:{error:'列表保存失败'}}))
  await dialog(page).getByRole('button',{name:'确定',exact:true}).click()
  await expect(dialog(page).locator('.dialog-error')).toContainText('小事已更新，切片列表保存失败')
  expect((await read(request)).every(event => event.meta.some(value => value.kind === '区域切片' && value.text === '训练新名'))).toBe(true)
  await page.unroute('**/writeslice'); await dialog(page).getByRole('button',{name:'确定',exact:true}).click()
  await expect(panel(page,'训练新名')).toBeVisible(); await expect(page.locator('dialog')).toHaveCount(0)
  await panel(page,'训练新名').getByRole('button',{name:'删除切片',exact:true}).click(); await dialog(page).getByRole('button',{name:'确定',exact:true}).click()
  await expect(page.locator('dialog')).toHaveCount(0); expect(await slices(request)).toEqual(['福利'])
  const after = await read(request)
  expect(after).toHaveLength(5); expect(after.every(event => !event.meta.some(value => value.kind === '区域切片'))).toBe(true)
  expect(ids.every(id => after.some(event => event.system.source_id === id))).toBe(true)
  expect(writes).not.toContain('/writeforest')
})

test('真实拖拽切换小事和闭环切片，保留状态、标签、timer，跨状态拒绝', async ({page,request}) => {
  await request.post('/writeslice',{data:['训练','福利']})
  const loop = loopTag(), id = await seed(request,'运行成员','训练','运行',[loop,{kind:'属性',text:'耗时:3s'},{kind:'属性',text:'评分:4'}])
  await request.post('/writetimer',{data:{key:String(id),state:'running'}})
  await seed(request,'待办甲','训练','待办',[loop]); await seed(request,'待办乙','训练','待办',[loop]); await seed(request,'福利同组','福利','待办',[loop])
  await seed(request,'归档同组','训练','归档',[loop])
  await seed(request,'目标运行组','训练','运行',[loopTag('另一组','b')])
  await open(page); const before = await read(request)
  await drag(page,card(panel(page,'训练'),'运行成员'),area(panel(page,'福利'),'待办'),false)
  await drag(page,card(panel(page,'训练'),'运行成员'),panel(page,'福利').locator('.slice-heading h2'))
  const changed = (await read(request)).find(event => event.system.source_id === id)
  expect(changed.meta.filter(value => value.kind !== '区域切片')).toEqual(before.find(event => event.system.source_id === id).meta.filter(value => value.kind !== '区域切片'))
  const [timer] = await (await request.post('/readtimer',{data:[String(id)]})).json(); expect(timer.state).toBe('running')
  await drag(page,area(panel(page,'训练')).locator('.loop > .group-head'),panel(page,'福利').locator('.slice-heading h2'))
  await expect(area(panel(page,'福利')).locator('.loop .count')).toHaveText('3 件')
  await expect(area(panel(page,'福利')).locator('.loop .event')).toHaveCount(3)
  await expect(area(panel(page,'训练'),'归档').locator('.loop .event')).toHaveCount(1)
  await drag(page,card(panel(page,'福利'),'运行成员'),panel(page).locator('.slice-heading h2'))
  await expect(card(panel(page),'运行成员')).toBeVisible()
  expect((await read(request)).find(event => event.system.source_id === id).meta.some(value => value.kind === '区域切片')).toBe(false)
  await drag(page,card(panel(page),'运行成员'),area(panel(page,'训练'),'运行').locator('.loop > .group-head'))
  const final = (await read(request)).find(event => event.system.source_id === id)
  expect(final.meta).toContainEqual(tag('训练')); expect(final.meta).toContainEqual(loop)
  expect(writes.every(path => path === '/writeevent')).toBe(true)
})

