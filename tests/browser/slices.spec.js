import {test, expect} from '@playwright/test'

const panel = (page, name = '') => page.locator('.small-page').filter({has: page.locator(`:scope > .slice-heading > h2`, {hasText: new RegExp(`^${name || '小事'}$`)})})
const area = (host, name = '待办') => host.locator(`.area[data-area="${name}"]`)
const card = (host, text) => host.locator('.event').filter({has: host.page().locator('.event-body', {hasText: text})})
const dialog = page => page.locator('dialog[open]').last()
const today = () => new Date().toLocaleDateString('sv-SE')
const tag = name => ({kind:'区域切片',text:name})
const loopTag = (name = '训练闭环', id = 'a') => ({kind:'闭环',text:`闭环#${id.repeat(32)}|${name}`})
const read = async request => (await (await request.post('/readevent',{data:[[]]})).json())[0]
const slices = async request => (await (await request.post('/readslice',{data:null})).json())
async function seed(request, text, slice = null, region = '待办', extra = []) {
  const response = await request.post('/writeevent',{data:[{system:{source_id:null,deleted:false},user:{event:text},meta:[{kind:'业务区域',text:region},...(!extra.some(value => value.kind === '属性' && value.text.startsWith('日期:')) ? [{kind:'属性',text:`日期:${today()}`}] : []),...(slice ? [tag(slice)] : []),...extra]}]})
  expect(response.ok()).toBe(true)
  return (await response.json())[0].source_id
}
async function open(page) {await page.goto('/'); await expect(page.locator('#message')).toHaveText('已读取')}
async function named(page, button, name) {
  await button.click(); await dialog(page).locator('input').fill(name); await dialog(page).getByRole('button',{name:'确定',exact:true}).click()
  await expect(page.locator('#message')).toHaveText('已保存'); await expect(page.locator('dialog')).toHaveCount(0)
}
async function record(page, button, text) {
  await button.click(); await page.getByLabel('小事正文',{exact:true}).fill(text); await dialog(page).getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.locator('#message')).toHaveText('已保存'); await expect(page.locator('dialog')).toHaveCount(0)
}
async function drag(page, source, target, accepted = true, position = 'inside') {
  await source.scrollIntoViewIfNeeded(); await target.scrollIntoViewIfNeeded()
  const a = await source.boundingBox(), b = await target.boundingBox()
  await page.mouse.move(a.x + Math.min(80,a.width / 2),a.y + a.height / 2); await page.mouse.down()
  await page.mouse.move(a.x + Math.min(80,a.width / 2) + 12,a.y + a.height / 2,{steps:5})
  const y = b.y + (position === 'before' ? 2 : position === 'after' ? b.height - 2 : b.height / 2)
  await page.mouse.move(b.x + Math.min(65,b.width / 2),y,{steps:15}); await page.mouse.move(b.x + Math.min(65,b.width / 2) + 1,y)
  if (accepted) await expect(target).toHaveClass(new RegExp(`drop-${position}`))
  else await expect(page.locator('.drop-inside,.drop-before,.drop-after')).toHaveCount(0)
  await page.mouse.up()
  if (accepted) await expect(page.locator('#message')).toHaveText('已保存')
}
